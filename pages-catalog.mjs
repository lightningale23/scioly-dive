// Splits the catalog for the static Pages build: the game bundle gets a prompt-only catalog, and each
// prompt's scored answer list becomes its own JSON file that the page fetches when a dive needs it.
// File names hash the prompt and its answers, so a changed list never comes from a stale cache.
import {questions} from './answer-bank.js';
import {packs} from './prompts.js';

const hash = text => {
  let a = 2166136261, b = 5381;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    a = Math.imul(a ^ c, 16777619) >>> 0;
    b = (Math.imul(b, 33) ^ c) >>> 0;
  }
  return a.toString(16).padStart(8, '0') + b.toString(16).padStart(8, '0');
};
// Compact rows: [canonical, aliases, points, fact?]. decodeBank in game.js turns them back into entries.
export const encodeBank = bank => bank.map(entry => [entry.canonical, entry.aliases, entry.points, ...(entry.fact ? [entry.fact] : [])]);

export function pagesCatalog() {
  const files = new Map();
  const events = questions.map(([event, rows]) => [event, rows.map(row => {
    const json = JSON.stringify(encodeBank(row.bank));
    const file = 'banks/' + hash(row.prompt + '\n' + json) + '.json';
    files.set(file, json);
    return {prompt: row.prompt, size: row.size, ...(row.since && {since: row.since}), file};
  })]);
  const source = '// Generated by pages-catalog.mjs for the static build.\n'
    + 'export const events = ' + JSON.stringify(events) + ';\nexport const packs = ' + JSON.stringify(packs) + ';\n';
  return {events, source, files};
}
