// Locks the One in a Krillion of every prompt in the Dailies from the first specialist day through
// [days] days from now (default 30), so later catalog changes can't move a played prompt's Krillion.
// Existing locks are kept as they are. Usage: npm run lock-krillions -- [days]
import {writeFileSync} from 'node:fs';
import {questionFor} from '../answer-bank.js';
import {krillionLocks} from '../catalog-data/krillion-locks.js';

export const FIRST_LOCKED_DAY = 20784;
const ahead = Number(process.argv[2] ?? 30);
const today = Math.floor(Date.now() / 86400000);
const locks = {...krillionLocks};
let added = 0;
for (let day = FIRST_LOCKED_DAY; day <= today + ahead; day++) for (let round = 0; round < 7; round++) {
  const question = questionFor(day, round, undefined, 'Daily');
  if (Object.hasOwn(locks, question.prompt)) continue;
  locks[question.prompt] = question.bank.find(entry => entry.points === 100).canonical;
  added++;
}
const body = Object.entries(locks).sort(([a], [b]) => a < b ? -1 : 1).map(([prompt, answer]) => '  ' + JSON.stringify(prompt) + ': ' + JSON.stringify(answer) + ',\n').join('');
writeFileSync(new URL('../catalog-data/krillion-locks.js', import.meta.url),
  '// Generated by scripts/lock-krillions.mjs (npm run lock-krillions). Locks are only ever added:\n'
  + '// each prompt’s One in a Krillion stays fixed from its first Daily on. Remove a lock only on purpose.\n'
  + 'export const krillionLocks = {\n' + body + '};\n');
console.log('Added', added, 'locks;', Object.keys(locks).length, 'in total, through', new Date((today + ahead) * 86400000).toISOString().slice(0, 10));
